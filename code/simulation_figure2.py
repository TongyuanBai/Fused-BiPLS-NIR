# -*- coding: utf-8 -*-
"""
Figure 2: regression coefficients estimated on simulated collinear spectra.

A smooth, strongly collinear spectral matrix (n = 100, p = 500) is generated by
Gaussian filtering of white noise. The true coefficient vector is piecewise
constant with two contiguous blocks. The panels show (a) the true coefficients
and the estimates of (b) LASSO, (c) PLS and (d) the fused lasso.

Usage (from the repository root):
    python code/simulation_figure2.py

Output: ./results/Figure_2.pdf
"""

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import cvxpy as cp
import matplotlib.pyplot as plt
import numpy as np
from scipy.ndimage import gaussian_filter1d
from sklearn.cross_decomposition import PLSRegression
from sklearn.linear_model import Lasso

RESULTS_DIR = Path(__file__).resolve().parents[1] / "results"

# ==========================================
# 1. Simulated collinear spectra
# ==========================================
np.random.seed(42)
n_samples, n_features = 100, 500

# Smoothing along the variable axis produces strong collinearity between
# adjacent variables, similar to broad NIR absorption bands.
X_base = np.random.randn(n_samples, n_features)
X = gaussian_filter1d(X_base, sigma=15, axis=1)

# Piecewise-constant true coefficients: two contiguous absorption blocks
beta_true = np.zeros(n_features)
beta_true[100:150] = 2.0
beta_true[320:380] = -1.5

noise = np.random.normal(0, 0.5, n_samples)
y = X @ beta_true + noise

# ==========================================
# 2. Estimators
# ==========================================
# (b) LASSO
lasso = Lasso(alpha=0.01, max_iter=10000)
lasso.fit(X, y)
beta_lasso = lasso.coef_

# (c) PLS
pls = PLSRegression(n_components=5)
pls.fit(X, y)
beta_pls = pls.coef_.ravel()

# (d) Fused lasso, solved with cvxpy:
#     least squares + l1 penalty on coefficients + l1 penalty on first differences
beta_fused = cp.Variable(n_features)
lambda_1 = 0.5    # sparsity penalty
lambda_tv = 5.0   # fusion (total-variation) penalty
objective = cp.Minimize(cp.sum_squares(y - X @ beta_fused)
                        + lambda_1 * cp.norm(beta_fused, 1)
                        + lambda_tv * cp.norm(cp.diff(beta_fused), 1))
cp.Problem(objective).solve()
beta_fused_val = beta_fused.value

# ==========================================
# 3. Figure
# ==========================================
plt.rcParams.update({
    "font.family": "serif",
    "font.serif": ["Times New Roman", "DejaVu Serif"],
    "font.size": 12,
    "axes.labelsize": 14,
    "axes.titlesize": 14,
    "xtick.labelsize": 11,
    "ytick.labelsize": 11,
    "axes.linewidth": 1.2,
    "lines.linewidth": 1.5,
})

fig, axes = plt.subplots(2, 2, figsize=(10, 7), constrained_layout=True)
axes = axes.flatten()


def plot_beta(ax, beta, title, label_letter):
    ax.plot(beta, color="black", alpha=0.8)
    ax.set_title(title, pad=10)
    ax.set_xlabel("Variable Index")
    ax.set_ylabel(r"Regression Coefficient ($\beta$)")
    ax.set_ylim(-2.5, 3.0)
    ax.axhline(0, color="gray", linestyle="--", linewidth=1)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.text(-0.1, 1.05, label_letter, transform=ax.transAxes,
            fontsize=16, fontweight="bold", va="top", ha="right")


plot_beta(axes[0], beta_true, r"True Coefficient ($\beta_{\mathrm{true}}$)", "(a)")
plot_beta(axes[1], beta_lasso, r"LASSO Estimate ($\hat{\beta}_{\mathrm{LASSO}}$)", "(b)")
plot_beta(axes[2], beta_pls, r"PLS Estimate ($\hat{\beta}_{\mathrm{PLS}}$)", "(c)")
plot_beta(axes[3], beta_fused_val, r"Fused Lasso Estimate ($\hat{\beta}_{\mathrm{Fused}}$)", "(d)")

RESULTS_DIR.mkdir(parents=True, exist_ok=True)
out_path = RESULTS_DIR / "Figure_2.pdf"
fig.savefig(out_path, format="pdf", dpi=300, bbox_inches="tight")
plt.close(fig)
print(f"Saved {out_path}")
